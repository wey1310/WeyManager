    parts = dob_str.split('/')
    if len(parts) == 3:
        day = int(parts[0])
        month = int(parts[1])
        for sm, sd, em, ed, z in zodiac_rules:
            if (month == sm and day >= sd) or (month == em and day <= ed):
                return z
    return "Libra"

